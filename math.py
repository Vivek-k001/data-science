import math

print(f"Pi: {math.pi}")
print(f"Euler's number: {math.e}")
print(f"Square root of 64: {math.sqrt(64)}")
print(f"2 raised to the power 3: {math.pow(2, 3)}")
print(f"Natural log of e: {math.log(math.e)}")
print(f"Base-10 log of 100: {math.log10(100)}")
print(f"Ceiling of 4.2: {math.ceil(4.2)}")
print(f"Floor of 4.8: {math.floor(4.8)}")
print(f"Factorial of 5: {math.factorial(5)}")
print(f"GCD of 28 and 36: {math.gcd(28, 36)}")

angle = math.radians(90)
print(f"Sin of 90 degrees: {math.sin(angle)}")
